-- Grain: one listing in one Inside Airbnb snapshot. The base fact behind every mart.
select
    l.listing_key,
    l.city,
    l.snapshot_date,
    l.listing_id,
    l.host_key,
    l.host_id,
    l.neighbourhood,
    l.neighbourhood_group,
    l.room_type,
    l.property_type,
    l.accommodates,
    l.bedrooms,
    l.price,
    l.has_price,
    l.minimum_nights,
    l.str_threshold_nights,
    l.is_entire_home,
    l.is_short_term,
    l.is_multi_listing_host,
    l.is_highly_available,
    l.is_recently_reviewed,
    l.is_frequently_booked,
    l.host_is_superhost,
    l.calculated_host_listings_count,
    l.licence_text,
    l.licence_status,
    l.availability_365,
    l.number_of_reviews,
    l.number_of_reviews_ltm,
    l.reviews_ltm_recount,
    l.reviews_file_is_this_snapshot,
    l.review_scores_rating,
    l.average_nights_stay,
    l.est_bookings_ltm,
    l.est_nights_per_booking,
    l.est_nights_ltm,
    l.est_occupancy_rate,
    l.est_revenue_ltm,
    l.iab_estimated_occupancy_l365d,
    l.iab_estimated_revenue_l365d,
    c.calendar_nights,
    c.available_nights_30,
    c.available_nights_90,
    c.available_nights_365,
    c.unavailable_nights_30,
    c.unavailable_nights_365,
    {{ safe_divide('c.unavailable_nights_30', 'least(c.calendar_nights, 30)') }} as unavailable_share_30,
    l.snapshot_seq,
    l.is_latest_snapshot
from {{ ref('int_listing_snapshots') }} as l
left join {{ ref('int_calendar_availability') }} as c
    on
        c.listing_key = l.listing_key
        and c.snapshot_date = l.snapshot_date
