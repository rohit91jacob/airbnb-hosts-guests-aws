-- Listings, one row per listing per snapshot. Prices are parsed from text here.
select
    city || ':' || cast(listing_id as varchar) as listing_key,
    city,
    snapshot_date,
    listing_id,
    host_id,
    city || ':' || cast(host_id as varchar) as host_key,
    last_scraped,
    listing_name,
    host_name,
    host_since,
    coalesce(host_is_superhost, false) as host_is_superhost,
    host_listings_count,
    calculated_host_listings_count,
    calculated_host_listings_count_entire_homes,
    calculated_host_listings_count_private_rooms,
    calculated_host_listings_count_shared_rooms,
    neighbourhood,
    neighbourhood_group,
    latitude,
    longitude,
    property_type,
    room_type,
    accommodates,
    bedrooms,
    beds,
    bathrooms,
    {{ parse_price('price_raw') }} as price,
    price_quote_checkin_date,
    price_quote_checkout_date,
    minimum_nights,
    maximum_nights,
    has_availability,
    availability_30,
    availability_60,
    availability_90,
    availability_365,
    number_of_reviews,
    number_of_reviews_ltm,
    number_of_reviews_l30d,
    iab_estimated_occupancy_l365d,
    iab_estimated_revenue_l365d,
    first_review,
    last_review,
    review_scores_rating,
    reviews_per_month,
    nullif(trim(license), '') as licence_text,
    {{ licence_status('license') }} as licence_status,
    instant_bookable
from {{ source('iab', 'listings') }}
